#!/usr/bin/env bash
# Turns full-size dish photos into the menu's web images.
#
#   bash scripts/build-menu-photos.sh <dir-with-<dish-id>.jpg|png|webp>
#
# File names must match the dish ids in src/data/menu.ts (e.g. cappuccino.jpg).
# Each photo is centre-cropped to the card's 16:10 and written as
# public/media/menu/<id>-400.webp and -800.webp. The list of dishes that
# have a photo is regenerated in src/data/menu-photos.ts.
set -euo pipefail

SRC="${1:?usage: build-menu-photos.sh <photo-dir>}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/public/media/menu"
mkdir -p "$OUT"

shopt -s nullglob
for f in "$SRC"/*.{jpg,jpeg,png,webp}; do
  id="$(basename "${f%.*}")"
  for w in 400 800; do
    ffmpeg -v error -y -i "$f" \
      -vf "crop='min(iw,ih*16/10)':'min(ih,iw*10/16)',scale=$w:-2:flags=lanczos" \
      -c:v libwebp -quality 76 "$OUT/$id-$w.webp"
  done
  echo "$id"
done

ids=$(ls "$OUT" | sed -n 's/-800\.webp$//p' | sort)
{
  echo "// Generated by scripts/build-menu-photos.sh — dishes with a photo in public/media/menu/."
  echo "export const menuPhotos: readonly string[] = ["
  for id in $ids; do echo "  '$id',"; done
  echo "]"
} > "$ROOT/src/data/menu-photos.ts"
echo "$(echo "$ids" | grep -c . || true) dishes have photos"
